"use strict";

// Builds the local Lucide subsets from scripts/vendor/lucide.full.min.js:
//   - shared-public/js/lucide.min.js, the classic script the manager UIs and the
//     classic console load (window.lucide.createIcons over <i data-lucide="...">);
//   - shared-public/vendor/lucide/0.454.0/icons.js, the ES module the new console
//     imports through console/ui/vendor.js, listed in shared-public/vendor/VENDOR.json
//     with its sha256 and size (07 §2.2).
// Names are sorted and nothing depends on the clock, so a re-run over an unchanged
// tree writes identical bytes; service-entry/test/console/vendor.test.js checks it.
//
//   node scripts/build-lucide-subset.cjs

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const LUCIDE_VERSION = "0.454.0";
const DEFAULT_ROOT = path.resolve(__dirname, "..");
const VENDOR_SCHEMA_VERSION = 1;
// Classic icons whose names are computed at runtime, so no data-lucide marker names them.
const dynamicIcons = ["circle-help", "circle-x", "image", "puzzle", "search-x", "triangle-alert", "zap"];
// Console icons the design-system primitives and the shell chrome need before any
// page names them: status and severity badges, close, copy, disclosure, external
// links, the viewer lock, search, the off-canvas menu and notifications.
const consoleBaseIcons = [
  "bell", "check", "chevron-down", "chevron-right", "circle-check", "circle-help", "circle-minus", "circle-x",
  "copy", "external-link", "info", "loader-circle", "lock", "menu", "search", "triangle-alert", "x",
];
// Console code names icons as icon("name"), <Icon name="name">, htm's
// <${Icon} name="name">, or an icon: "name" / icon="name" prop.
const CONSOLE_ICON_PATTERNS = [
  /\bicon\(\s*["']([a-z0-9-]+)["']\s*\)/g,
  /<(?:Icon|\$\{\s*Icon\s*\})\s[^>]*?\bname=["']([a-z0-9-]+)["']/g,
  /(?<![\w-])icon\s*[:=]\s*["']([a-z0-9-]+)["']/g,
];
const LICENSE_FROM = "npm:lucide@0.454.0/LICENSE (copied by hand)";

function layout(root) {
  const vendorRoot = path.join(root, "shared-public", "vendor");
  return {
    sourceFile: path.join(root, "scripts", "vendor", "lucide.full.min.js"),
    classicOutput: path.join(root, "shared-public", "js", "lucide.min.js"),
    classicScanRoots: [
      path.join(root, "shared-public", "js"),
      path.join(root, "vllm-manager", "public"),
      path.join(root, "llama-manager", "public"),
    ],
    consoleRoot: path.join(root, "service-entry", "console"),
    vendorRoot,
    vendorDir: `lucide/${LUCIDE_VERSION}`,
    vendorManifest: path.join(vendorRoot, "VENDOR.json"),
  };
}

function walk(directory, pattern, skip = new Set()) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) return entry.name === "node_modules" ? [] : walk(full, pattern, skip);
    return pattern.test(entry.name) && !skip.has(full) ? [full] : [];
  });
}

function exportName(iconName) {
  return iconName.split("-").filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join("");
}

/** Icon names the classic UIs use through data-lucide markers, plus the dynamic ones. */
function classicIconNames(root = DEFAULT_ROOT) {
  const paths = layout(root);
  const names = new Set(dynamicIcons);
  paths.classicScanRoots.flatMap((directory) => walk(directory, /\.(?:html|js)$/, new Set([paths.classicOutput]))).forEach((file) => {
    const source = fs.readFileSync(file, "utf8");
    for (const match of source.matchAll(/data-lucide=["']([a-z0-9-]+)["']/g)) names.add(match[1]);
  });
  return [...names].sort();
}

/** Icon names the new console uses, plus the base set its primitives need. */
function consoleIconNames(root = DEFAULT_ROOT) {
  const names = new Set(consoleBaseIcons);
  walk(layout(root).consoleRoot, /\.js$/).forEach((file) => {
    const source = fs.readFileSync(file, "utf8");
    for (const pattern of CONSOLE_ICON_PATTERNS) {
      for (const match of source.matchAll(pattern)) names.add(match[1]);
    }
  });
  return [...names].sort();
}

function loadLucide(sourceFile) {
  delete require.cache[require.resolve(sourceFile)];
  return require(sourceFile);
}

function pickIcons(lucide, names) {
  return names.map((name) => {
    const key = exportName(name);
    if (!lucide[key]) throw new Error(`Missing Lucide export ${key} for ${name}`);
    return { name, key, spec: lucide[key] };
  });
}

function classicRuntime(picked) {
  const icons = {};
  for (const { key, spec } of picked) icons[key] = spec;
  return `/**\n * @license lucide v${LUCIDE_VERSION} - ISC\n * Local subset generated by scripts/build-lucide-subset.cjs (${Object.keys(icons).length} icons).\n */\n(function(g){\"use strict\";const icons=${JSON.stringify(icons)};const ns=\"http://www.w3.org/2000/svg\";function node(spec){const el=document.createElementNS(ns,spec[0]);Object.entries(spec[1]||{}).forEach(([key,value])=>el.setAttribute(key,String(value)));(spec[2]||[]).forEach(child=>el.appendChild(node(child)));return el}function key(name){return String(name||\"\").split(\"-\").filter(Boolean).map(part=>part[0].toUpperCase()+part.slice(1)).join(\"\")}function createIcons(options={}){const attrs=options.attrs||{};document.querySelectorAll(\"i[data-lucide]\").forEach(marker=>{const name=marker.getAttribute(\"data-lucide\");const spec=icons[key(name)];if(!spec)return;const svg=node(spec);for(const attr of marker.attributes){if(attr.name===\"data-lucide\")continue;if(attr.name===\"class\")svg.setAttribute(\"class\",[svg.getAttribute(\"class\"),attr.value].filter(Boolean).join(\" \"));else svg.setAttribute(attr.name,attr.value)}Object.entries(attrs).forEach(([attr,value])=>svg.setAttribute(attr,String(value)));svg.classList.add(\"lucide\",\"lucide-\"+name);marker.replaceWith(svg)})}g.lucide={icons,createIcons}})(window);\n`;
}

// Every Lucide icon shares one set of <svg> attributes, so the module states it
// once and keeps only the child nodes per icon; that keeps the console's static
// vendor code inside the 07 §11 budget.
function consoleModule(picked) {
  const defaultAttributes = picked.length ? picked[0].spec[1] : {};
  const lines = picked.map(({ name, spec }) => {
    if (spec[0] !== "svg" || JSON.stringify(spec[1]) !== JSON.stringify(defaultAttributes)) {
      throw new Error(`Lucide icon ${name} does not use the shared <svg> attributes`);
    }
    return `  ${JSON.stringify(name)}: ${JSON.stringify(spec[2] || [])},`;
  });
  return [
    "/**",
    ` * @license lucide v${LUCIDE_VERSION} - ISC`,
    ` * Local ES module subset generated by scripts/build-lucide-subset.cjs (${picked.length} icons).`,
    " * icons maps a kebab-case Lucide name to the child nodes ([tag, attributes]) of",
    " * its <svg>; the <svg> element itself carries defaultAttributes.",
    " */",
    `export const defaultAttributes = ${JSON.stringify(defaultAttributes)};`,
    "export const icons = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

function sha256(content) {
  return crypto.createHash("sha256").update(content).digest("hex");
}

/** A VENDOR.json file record for content written to <dir>/<relativePath>. */
function fileRecord(relativePath, content, extra = {}) {
  const buffer = Buffer.isBuffer(content) ? content : Buffer.from(content, "utf8");
  return { path: relativePath, ...extra, sha256: sha256(buffer), bytes: buffer.length };
}

function compareText(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

/**
 * The canonical VENDOR.json shape both writers (this script and
 * vendor-browser-libs.mjs) produce: packages sorted by name, and importMap
 * rebuilt from every package's entries (05 §12.1 builds the portal's import map
 * from it). Keys outside the schema are kept after the known ones.
 */
function normalizeVendorManifest(manifest) {
  const { schemaVersion, asOf, staleAfterDays, packages = [], styles = {}, ...rest } = manifest;
  delete rest.importMap;
  const sorted = [...packages].sort((a, b) => compareText(a.name, b.name));
  const importMap = {};
  for (const entry of sorted) {
    for (const [specifier, file] of Object.entries(entry.entries || {})) importMap[specifier] = `${entry.dir}/${file}`;
  }
  const sortedKeys = (object) => Object.fromEntries(Object.keys(object).sort(compareText).map((key) => [key, object[key]]));
  return {
    schemaVersion: schemaVersion ?? VENDOR_SCHEMA_VERSION,
    asOf,
    staleAfterDays,
    packages: sorted,
    styles: sortedKeys(styles),
    importMap: sortedKeys(importMap),
    ...rest,
  };
}

function serializeVendorManifest(manifest) {
  return `${JSON.stringify(normalizeVendorManifest(manifest), null, 2)}\n`;
}

function readVendorManifest(file) {
  if (!fs.existsSync(file)) {
    throw new Error(`${file} is missing; run node scripts/vendor-browser-libs.mjs first, it creates the vendor manifest`);
  }
  return JSON.parse(fs.readFileSync(file, "utf8").replace(/^\uFEFF/, ""));
}

/**
 * Computes every output without writing: [{ file, content }] for the classic
 * script, the console module and VENDOR.json with the lucide entry refreshed.
 */
function buildLucideSubsets(root = DEFAULT_ROOT) {
  const paths = layout(root);
  const lucide = loadLucide(paths.sourceFile);
  const classic = pickIcons(lucide, classicIconNames(root));
  const consolePicked = pickIcons(lucide, consoleIconNames(root));
  const classicContent = classicRuntime(classic);
  const moduleContent = consoleModule(consolePicked);

  const licenseFile = path.join(paths.vendorRoot, paths.vendorDir, "LICENSE");
  if (!fs.existsSync(licenseFile)) {
    throw new Error(`${licenseFile} is missing; copy the ISC LICENSE of lucide@${LUCIDE_VERSION} there once by hand`);
  }
  const manifest = readVendorManifest(paths.vendorManifest);
  const lucideEntry = {
    name: "lucide",
    version: LUCIDE_VERSION,
    license: "ISC",
    source: "scripts/vendor/lucide.full.min.js",
    generated: "scripts/build-lucide-subset.cjs",
    dir: paths.vendorDir,
    entries: { lucide: "icons.js" },
    files: [
      fileRecord("icons.js", moduleContent, { from: "scripts/vendor/lucide.full.min.js" }),
      fileRecord("LICENSE", fs.readFileSync(licenseFile), { from: LICENSE_FROM }),
    ],
  };
  const packages = (manifest.packages || []).filter((entry) => entry.name !== "lucide").concat(lucideEntry);
  return {
    classicCount: classic.length,
    consoleCount: consolePicked.length,
    outputs: [
      { file: paths.classicOutput, content: classicContent },
      { file: path.join(paths.vendorRoot, paths.vendorDir, "icons.js"), content: moduleContent },
      { file: paths.vendorManifest, content: serializeVendorManifest({ ...manifest, packages }) },
    ],
  };
}

function main(root = DEFAULT_ROOT) {
  const result = buildLucideSubsets(root);
  for (const { file, content } of result.outputs) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
  const [classic, module_] = result.outputs;
  console.log(`Wrote ${classic.file} with ${result.classicCount} icons (${Buffer.byteLength(classic.content)} bytes).`);
  console.log(`Wrote ${module_.file} with ${result.consoleCount} icons (${Buffer.byteLength(module_.content)} bytes) and updated VENDOR.json.`);
}

if (require.main === module) main();

module.exports = {
  LUCIDE_VERSION,
  buildLucideSubsets,
  classicIconNames,
  consoleBaseIcons,
  consoleIconNames,
  fileRecord,
  main,
  normalizeVendorManifest,
  readVendorManifest,
  serializeVendorManifest,
  sha256,
};
