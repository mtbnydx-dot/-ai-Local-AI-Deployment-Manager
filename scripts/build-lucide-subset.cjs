"use strict";

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const sourceFile = path.join(__dirname, "vendor", "lucide.full.min.js");
const outputFile = path.join(root, "shared-public", "js", "lucide.min.js");
const scanRoots = [
  path.join(root, "shared-public", "js"),
  path.join(root, "vllm-manager", "public"),
  path.join(root, "llama-manager", "public"),
];
const dynamicIcons = ["circle-help", "circle-x", "image", "puzzle", "search-x", "triangle-alert", "zap"];

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(full);
    return /\.(?:html|js)$/.test(entry.name) && full !== outputFile ? [full] : [];
  });
}

function exportName(iconName) {
  return iconName.split("-").filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join("");
}

const names = new Set(dynamicIcons);
scanRoots.flatMap(walk).forEach((file) => {
  const source = fs.readFileSync(file, "utf8");
  for (const match of source.matchAll(/data-lucide=["']([a-z0-9-]+)["']/g)) names.add(match[1]);
});

delete require.cache[require.resolve(sourceFile)];
const lucide = require(sourceFile);
const icons = {};
for (const name of [...names].sort()) {
  const key = exportName(name);
  if (!lucide[key]) throw new Error(`Missing Lucide export ${key} for ${name}`);
  icons[key] = lucide[key];
}

const runtime = `/**\n * @license lucide v0.454.0 - ISC\n * Local subset generated by scripts/build-lucide-subset.cjs (${Object.keys(icons).length} icons).\n */\n(function(g){\"use strict\";const icons=${JSON.stringify(icons)};const ns=\"http://www.w3.org/2000/svg\";function node(spec){const el=document.createElementNS(ns,spec[0]);Object.entries(spec[1]||{}).forEach(([key,value])=>el.setAttribute(key,String(value)));(spec[2]||[]).forEach(child=>el.appendChild(node(child)));return el}function key(name){return String(name||\"\").split(\"-\").filter(Boolean).map(part=>part[0].toUpperCase()+part.slice(1)).join(\"\")}function createIcons(options={}){const attrs=options.attrs||{};document.querySelectorAll(\"i[data-lucide]\").forEach(marker=>{const name=marker.getAttribute(\"data-lucide\");const spec=icons[key(name)];if(!spec)return;const svg=node(spec);for(const attr of marker.attributes){if(attr.name===\"data-lucide\")continue;if(attr.name===\"class\")svg.setAttribute(\"class\",[svg.getAttribute(\"class\"),attr.value].filter(Boolean).join(\" \"));else svg.setAttribute(attr.name,attr.value)}Object.entries(attrs).forEach(([attr,value])=>svg.setAttribute(attr,String(value)));svg.classList.add(\"lucide\",\"lucide-\"+name);marker.replaceWith(svg)})}g.lucide={icons,createIcons}})(window);\n`;
fs.writeFileSync(outputFile, runtime);
console.log(`Wrote ${outputFile} with ${Object.keys(icons).length} icons (${Buffer.byteLength(runtime)} bytes).`);
